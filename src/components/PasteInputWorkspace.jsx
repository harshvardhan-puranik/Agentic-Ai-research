import React, { useState } from 'react';
import {
  FileCode,
  CheckCircle,
  AlertCircle,
  Sparkles,
  ArrowRight,
  ExternalLink,
  BookOpen,
  Upload,
  Cpu,
  FileText,
  HelpCircle,
  ShieldAlert
} from 'lucide-react';
import { validateOutput1Payload, SAMPLE_OUTPUT_1 } from '../utils/paperAnalysisEngine.js';

export default function PasteInputWorkspace({
  importedPayload,
  onImportSuccess,
  customInstructions,
  setCustomInstructions,
  onStartAnalysis,
  isAnalyzing,
  onNavigateToPdf
}) {
  const [jsonText, setJsonText] = useState(
    importedPayload ? JSON.stringify(importedPayload, null, 2) : ''
  );
  const [validationResult, setValidationResult] = useState(
    importedPayload ? validateOutput1Payload(importedPayload) : null
  );
  const [parseError, setParseError] = useState(null);

  const handleValidateAndImport = (textToValidate) => {
    const raw = textToValidate !== undefined ? textToValidate : jsonText;
    setParseError(null);

    if (!raw || !raw.trim()) {
      setValidationResult({ valid: false, errors: ['Please paste your Output 1 JSON string from Module 1.'] });
      return;
    }

    try {
      const parsed = JSON.parse(raw);
      const res = validateOutput1Payload(parsed);
      setValidationResult(res);

      if (res.valid) {
        onImportSuccess(res.data);
      }
    } catch (e) {
      setParseError(e.message);
      setValidationResult({
        valid: false,
        errors: [`Syntax error parsing JSON: ${e.message}. Ensure you copied the full Output 1 JSON payload.`]
      });
    }
  };

  const handleLoadSample = () => {
    const formatted = JSON.stringify(SAMPLE_OUTPUT_1, null, 2);
    setJsonText(formatted);
    handleValidateAndImport(formatted);
  };

  const handleClear = () => {
    setJsonText('');
    setValidationResult(null);
    setParseError(null);
  };

  const currentData = validationResult?.valid ? validationResult.data : importedPayload;

  return (
    <div className="max-w-6xl mx-auto px-4 sm:px-6 py-8 space-y-8">
      {/* Header */}
      <div className="border-b border-[#D1DFD6] pb-5">
        <div className="inline-flex items-center space-x-1.5 text-xs font-mono uppercase tracking-wider text-[#176B50] font-semibold bg-[#E8F1EA] px-2.5 py-1 rounded mb-2">
          <FileCode className="w-3.5 h-3.5" />
          <span>Module 2 Ingestion Portal</span>
        </div>
        <h1 className="text-2xl sm:text-3xl font-serif font-bold text-[#123D32]">
          Paste Output 1 JSON from Module 1
        </h1>
        <p className="text-sm text-stone-600 mt-1 max-w-3xl">
          Module 2 accepts the canonical Output 1 JSON generated by Website 1. Topic metadata, paper DOIs, authors, and source URLs are automatically extracted and preserved.
        </p>
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-12 gap-8">
        {/* Left Column: Paste Area & Instructions */}
        <div className="lg:col-span-7 space-y-6">
          <div className="bg-white border border-[#D1DFD6] rounded-xl p-5 shadow-sm space-y-4">
            <div className="flex items-center justify-between">
              <label htmlFor="output1-input" className="block text-xs font-bold uppercase tracking-wider text-[#123D32]">
                Output 1 JSON Payload *
              </label>
              <div className="flex items-center space-x-2">
                <button
                  type="button"
                  onClick={handleLoadSample}
                  className="flex items-center space-x-1 text-xs font-semibold text-[#176B50] hover:text-[#123D32] bg-[#E8F1EA] hover:bg-[#D7E8DC] px-2.5 py-1 rounded transition-colors cursor-pointer"
                  title="Load pre-built benchmark Output 1 with 5 real papers"
                >
                  <Sparkles className="w-3.5 h-3.5" />
                  <span>Load Sample Output 1</span>
                </button>
                {jsonText && (
                  <button
                    type="button"
                    onClick={handleClear}
                    className="text-xs text-stone-500 hover:text-red-700 px-2 py-1 transition-colors cursor-pointer"
                  >
                    Clear
                  </button>
                )}
              </div>
            </div>

            <div className="relative">
              <textarea
                id="output1-input"
                rows={12}
                value={jsonText}
                onChange={(e) => {
                  setJsonText(e.target.value);
                  if (validationResult) setValidationResult(null);
                }}
                placeholder={`{\n  "schema_version": "1.0.0",\n  "project_id": "rs-proj-xxxx",\n  "research_topic": "Attention Mechanisms in Deep Learning",\n  "papers": [\n    {\n      "paper_id": "rs-paper-001",\n      "title": "...",\n      "doi": "10.xxxx/...",\n      ...\n    }\n  ]\n}`}
                className="w-full font-mono text-xs p-3.5 border border-[#D1DFD6] rounded-lg focus:outline-none focus:ring-2 focus:ring-[#176B50] focus:border-[#176B50] bg-[#FAFCFA] text-[#1D2A24]"
              />
            </div>

            <div className="flex items-center justify-between pt-1">
              <p className="text-[11px] text-stone-500 italic">
                * Schema v1.0.0 verified. Do not re-enter metadata manually.
              </p>
              <button
                type="button"
                onClick={() => handleValidateAndImport()}
                className="bg-[#176B50] hover:bg-[#123D32] text-white px-4 py-2 rounded-md font-semibold text-xs shadow transition-colors cursor-pointer"
              >
                Validate &amp; Ingest Output 1
              </button>
            </div>
          </div>

          {/* Optional Analysis Instructions */}
          <div className="bg-white border border-[#D1DFD6] rounded-xl p-5 shadow-sm space-y-3">
            <div className="flex items-center justify-between">
              <label htmlFor="instructions-input" className="block text-xs font-bold uppercase tracking-wider text-[#123D32]">
                Custom Analysis Focus (Optional)
              </label>
              <span className="text-[11px] text-stone-500 font-mono">Optional Guidance</span>
            </div>
            <textarea
              id="instructions-input"
              rows={3}
              value={customInstructions}
              onChange={(e) => setCustomInstructions(e.target.value)}
              placeholder="e.g. Focus on sub-quadratic attention scaling, memory overhead comparison, and empirical BLEU/Accuracy gains on standard benchmarks."
              className="w-full text-xs p-3 border border-[#D1DFD6] rounded-lg focus:outline-none focus:ring-2 focus:ring-[#176B50] focus:border-[#176B50] bg-white text-[#1D2A24]"
            />
            <p className="text-[11px] text-stone-500">
              Directs the structured extractor to emphasize specific theoretical properties, hardware requirements, or evaluation criteria during processing.
            </p>
          </div>
        </div>

        {/* Right Column: Validation Status & Imported Preview */}
        <div className="lg:col-span-5 space-y-6">
          {/* Validation Feedback Card */}
          {validationResult && (
            <div
              className={`p-4 rounded-xl border ${
                validationResult.valid
                  ? 'bg-[#E8F1EA] border-[#B6D6BE] text-[#123D32]'
                  : 'bg-red-50 border-red-200 text-red-900'
              }`}
            >
              <div className="flex items-start space-x-3">
                {validationResult.valid ? (
                  <CheckCircle className="w-5 h-5 text-emerald-700 mt-0.5 flex-shrink-0" />
                ) : (
                  <AlertCircle className="w-5 h-5 text-red-600 mt-0.5 flex-shrink-0" />
                )}
                <div className="space-y-1">
                  <h4 className="font-semibold text-sm">
                    {validationResult.valid
                      ? 'Output 1 Schema Validated Successfully'
                      : 'Schema Validation Error'}
                  </h4>
                  {validationResult.valid ? (
                    <p className="text-xs text-[#1A4F42]">
                      Successfully registered <strong>{validationResult.paperCount} academic papers</strong> for project{' '}
                      <code className="bg-emerald-100 px-1 py-0.5 rounded font-mono text-[11px]">
                        {validationResult.project_id}
                      </code>
                      .
                    </p>
                  ) : (
                    <ul className="text-xs space-y-1 list-disc list-inside text-red-700">
                      {validationResult.errors.map((err, i) => (
                        <li key={i}>{err}</li>
                      ))}
                    </ul>
                  )}
                </div>
              </div>
            </div>
          )}

          {/* Imported Papers Preview */}
          {currentData && currentData.papers && (
            <div className="bg-white border border-[#D1DFD6] rounded-xl p-5 shadow-sm space-y-4">
              <div className="flex items-center justify-between border-b border-stone-200 pb-3">
                <div>
                  <span className="text-[11px] font-mono text-emerald-800 uppercase block font-semibold">
                    Project {currentData.project_id}
                  </span>
                  <h3 className="font-serif font-bold text-base text-[#123D32]">
                    {currentData.research_topic}
                  </h3>
                </div>
                <span className="bg-[#E8F1EA] text-[#123D32] px-2.5 py-1 rounded text-xs font-mono font-bold">
                  {currentData.papers.length} Papers
                </span>
              </div>

              {currentData.research_question && (
                <div className="text-xs text-stone-600 italic bg-[#F7FAF8] p-2.5 rounded border border-[#E0ECE4]">
                  "{currentData.research_question}"
                </div>
              )}

              {/* Paper List Snippets */}
              <div className="space-y-2.5 max-h-[340px] overflow-y-auto pr-1">
                {currentData.papers.map((p, idx) => {
                  const isOa = p.open_access_status === 'gold' || p.open_access_status === 'green';
                  return (
                    <div
                      key={p.paper_id || idx}
                      className="p-3 bg-[#F8FAF9] border border-[#E0ECE4] rounded-lg text-xs space-y-1 hover:border-[#176B50] transition-colors"
                    >
                      <div className="flex items-center justify-between">
                        <span className="font-mono text-[10px] text-stone-500 font-bold">
                          #{idx + 1} • {p.paper_id}
                        </span>
                        <div className="flex items-center space-x-1.5">
                          <span
                            className={`px-1.5 py-0.2 rounded text-[10px] font-semibold ${
                              isOa ? 'bg-emerald-100 text-emerald-800' : 'bg-amber-100 text-amber-800'
                            }`}
                          >
                            {isOa ? 'Open Access' : 'Abstract Only'}
                          </span>
                          <span className="text-[10px] font-mono text-stone-400">{p.source || 'OpenAlex'}</span>
                        </div>
                      </div>

                      <h4 className="font-serif font-semibold text-[#123D32] line-clamp-1">
                        {p.title}
                      </h4>

                      <div className="flex items-center space-x-2 text-[11px] text-stone-500">
                        <span>{Array.isArray(p.authors) ? p.authors.slice(0, 2).join(', ') : 'Authors'}</span>
                        <span>•</span>
                        <span>{p.year || 2024}</span>
                        {p.doi && (
                          <>
                            <span>•</span>
                            <span className="font-mono text-[10px] truncate max-w-[130px]">{p.doi}</span>
                          </>
                        )}
                      </div>
                    </div>
                  );
                })}
              </div>

              {/* Action Buttons */}
              <div className="pt-2 flex flex-col sm:flex-row gap-2.5">
                <button
                  type="button"
                  onClick={onStartAnalysis}
                  disabled={isAnalyzing}
                  className="flex-1 flex items-center justify-center space-x-2 bg-[#123D32] hover:bg-[#176B50] disabled:bg-stone-400 text-white py-2.5 px-4 rounded-lg font-bold text-xs shadow transition-all cursor-pointer"
                >
                  <Cpu className="w-4 h-4 text-emerald-300" />
                  <span>{isAnalyzing ? 'Executing 17-Step Pipeline...' : 'Execute Deep Paper Analysis'}</span>
                  <ArrowRight className="w-4 h-4" />
                </button>

                <button
                  type="button"
                  onClick={onNavigateToPdf}
                  className="flex items-center justify-center space-x-1.5 bg-[#E8F1EA] hover:bg-[#D7E8DC] text-[#123D32] py-2.5 px-3 rounded-lg font-semibold text-xs transition-colors cursor-pointer"
                  title="Upload full-text PDF for any paper behind paywalls"
                >
                  <Upload className="w-3.5 h-3.5 text-[#176B50]" />
                  <span>Upload PDFs</span>
                </button>
              </div>
            </div>
          )}

          {/* Assistance Box */}
          {!currentData && (
            <div className="bg-[#F8FAF9] border border-dashed border-[#D1DFD6] rounded-xl p-6 text-center space-y-3">
              <div className="w-10 h-10 rounded-full bg-[#E8F1EA] text-[#176B50] flex items-center justify-center mx-auto">
                <HelpCircle className="w-5 h-5" />
              </div>
              <h4 className="font-serif font-bold text-sm text-[#123D32]">
                Need Sample Data from Module 1?
              </h4>
              <p className="text-xs text-stone-600 leading-relaxed">
                Click <strong>"Load Sample Output 1"</strong> above to instantly load a verified benchmark payload with 5 real peer-reviewed attention mechanism papers.
              </p>
              <button
                type="button"
                onClick={handleLoadSample}
                className="inline-flex items-center space-x-1.5 bg-[#176B50] hover:bg-[#123D32] text-white px-3.5 py-1.5 rounded-md font-semibold text-xs shadow-sm transition-colors cursor-pointer"
              >
                <Sparkles className="w-3.5 h-3.5" />
                <span>Load Sample Dataset</span>
              </button>
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
